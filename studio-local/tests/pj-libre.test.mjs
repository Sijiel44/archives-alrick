import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { PJ_SOURCE_KEY } from '../store.mjs';
import { browserFixture } from './browser.mjs';

test('Création libre d’un PJ, contrôle M02, fiche jouable et sauvegarde v9', { timeout: 45000 }, async t => {
  const fixture = await browserFixture(t);
  const { page } = await fixture.open('pj-libre');
  await page.goto(fixture.url);
  await page.locator('#campaign-name').fill('La campagne du pont suspendu');
  await page.locator('#starting-level').fill('10');
  await page.locator('#create-campaign-submit').click();
  await page.locator('#free-pj').click();
  const modal = page.locator('#pj-free-dialog');
  const review = page.locator('#pj-free-review-panel');
  const name = 'Ysandre du Pont';
  await modal.getByLabel('Nom du PJ').fill(name);
  assert.equal(await modal.getByLabel('Niveau', { exact: true }).inputValue(), '10');
  await modal.getByLabel('Métier ou rôle').fill('Cartographe');
  await modal.getByText('Écrire le récit et les liens du PJ', { exact: false }).click();
  await modal.getByLabel('Histoire personnelle').fill('CANARI_PJ_LIBRE Collectionne les anciennes cartes.');
  await modal.getByLabel('Physique de départ').fill('5');
  await modal.getByRole('button', { name: 'Vérifier le budget et la fiche' }).click();
  await modal.getByRole('alert').getByText(/12 points/).waitFor();
  assert.equal(await review.isVisible(), false);
  await modal.getByLabel('Agilité de départ').fill('1');
  assert.equal(await modal.getByLabel('Physique finale').inputValue(), '5');
  await modal.getByLabel('Physique finale').fill('8');
  await modal.getByText('Choisir les maîtrises').click();
  await modal.getByLabel('Magie', { exact: true }).fill('2');
  await modal.getByLabel('Niveau', { exact: true }).fill('1');
  await modal.getByRole('button', { name: 'Vérifier le budget et la fiche' }).click();
  await modal.getByRole('alert').getByText(/Dépassement du budget/).waitFor();
  assert.equal(await review.isVisible(), false);
  await modal.getByLabel('Niveau', { exact: true }).fill('10');
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await modal.evaluate(el => el.scrollWidth <= el.clientWidth), `création libre à ${width}px`);
  }
  await modal.getByRole('button', { name: 'Vérifier le budget et la fiche' }).click();
  await review.getByText(/5 \/ 54 points · 49 en réserve/).waitFor();
  assert.equal(await page.locator('#character-list li').count(), 0);
  await review.getByRole('button', { name: 'Revenir aux choix' }).click();
  assert.equal(await modal.getByLabel('Magie', { exact: true }).inputValue(), '2');
  await modal.getByRole('button', { name: 'Vérifier le budget et la fiche' }).click();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'pj-free-preview-title');
  await review.getByRole('button', { name: 'Créer le PJ', exact: true }).click();
  await modal.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: `Ouvrir le profil 5d6 de ${name}` }).click();
  await page.locator('#resource-profile').getByText('Cartographe', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Préparer la fiche joueur' }).click();
  await page.locator('#player-share-fields').getByRole('checkbox', { name: 'Niveau et métier' }).check();
  const playerPreview = await page.locator('#player-share-preview iframe').getAttribute('srcdoc');
  assert.match(playerPreview, /Cartographe/);
  assert.doesNotMatch(playerPreview, /CANARI_PJ_LIBRE/);
  await page.keyboard.press('Escape');
  await page.locator('#nav-backups').click();
  const [file] = await Promise.all([page.waitForEvent('download'), page.locator('#export-backup').click()]);
  const archive = JSON.parse(await readFile(await file.path()));
  const [character] = archive.payload.campaign.characters;
  const source = character[PJ_SOURCE_KEY];
  assert.equal(archive.version, 9);
  assert.equal(character.level, 10);
  assert.equal(source.xp, 2025);
  assert.deepEqual(source.development.startingStats, { physique: 5, agilite: 1, esprit: 3, presence: 3 });
  assert.equal(source.stats.physique, 8);
  assert.deepEqual(source.masteries, { magie: 2 });
  assert.equal(source.manaMax, source.pvMax);
});
